// 文件职责：浏览器端合成注册、角色创建、mock 聊天和响应式截图验收，不代表真实模型质量。
import { test, expect } from '@playwright/test'

// 浏览器测试回调：先准备合成数据，再操作页面，最后通过 expect 判断可见结果。
test('register, create role, configure mock, publish and private AI chat', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('/')
  await page.getByText('第一次来？使用邀请码注册').click()
  await page.locator('uni-input').filter({hasText:'账号（至少 3 位）'}).locator('input').fill('e2e_' + Date.now())
  await page.locator('uni-input').filter({hasText:'密码（注册至少 10 位）'}).locator('input').fill('test-password-123')
  await page.locator('uni-input').filter({hasText:'你的昵称'}).locator('input').fill('测试体验者')
  await page.locator('uni-input').filter({hasText:'邀请码'}).locator('input').fill('local-demo')
  await page.getByText('创建账号', {exact:true}).click()
  await expect(page.getByText('你的社交空间')).toBeVisible()
  await page.getByText('创建第一个角色 →').click()
  await page.locator('uni-input').filter({hasText:'角色名称'}).locator('input').fill('林间测试')
  await page.locator('uni-textarea').filter({hasText:'公开简介'}).locator('textarea').fill('喜欢散步和真诚的对话。')
  const modal = page.locator('.modal')
  const switches = modal.locator('uni-switch')
  await switches.nth(0).click()
  await switches.nth(1).click()
  await switches.nth(2).click()
  await page.getByText('保存角色', {exact:true}).click()
  await expect(page.locator('.role-card').getByText('林间测试', {exact:true})).toBeVisible()
  await page.locator('.nav-item').filter({hasText:'模型与设置'}).click()
  await page.getByText('添加连接', {exact:true}).click()
  await expect(page.locator('.connection-row').getByText('demo-role', {exact:true})).toBeVisible()
  await page.locator('.nav-item').filter({hasText:'社区'}).click()
  await page.locator('.composer textarea').fill('这是自动化测试发布的一条合成动态。')
  await page.getByText('发布动态 ↗', {exact:true}).click()
  await expect(page.locator('.post-body').filter({hasText:'这是自动化测试发布的一条合成动态。'}).first()).toBeVisible()
  await page.screenshot({path:'test-results/community-desktop.png',fullPage:true})
  await page.locator('.nav-item').filter({hasText:'角色广场'}).click()
  const card = page.locator('.role-card').filter({hasText:'林间测试'}).last()
  await card.getByText('与 AI 聊 ✧', {exact:true}).click()
  await expect(page.locator('.chat-privacy')).toContainText('角色拥有者无法查看或接管此会话。')
  await page.locator('.chat-compose textarea').fill('你好，很高兴认识你')
  await page.getByText('发送 ↗', {exact:true}).click()
  await expect(page.locator('.bubble').filter({hasText:'本地演示，非真实模型'})).toBeVisible({timeout:20000})
  await page.screenshot({path:'test-results/chat-desktop.png',fullPage:true})
  await page.setViewportSize({width:390,height:844})
  await page.screenshot({path:'test-results/chat-mobile.png',fullPage:true})
  expect(errors).toEqual([])
})
